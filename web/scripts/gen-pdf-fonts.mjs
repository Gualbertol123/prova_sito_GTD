// Embeds the Inter font files the server-side PDF uses into a module, so the
// Netlify Function carries its fonts with it (no file lookups at run time).
// Run by `npm run build`; the output is generated, not committed.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, "..", "node_modules", "@fontsource", "inter", "files");
const weights = [400, 500, 600, 700, 800];
const out = path.join(here, "..", "netlify", "lib", "fonts.generated.mjs");

let src = "// Generated by scripts/gen-pdf-fonts.mjs — do not edit.\n";
// Latin, plus Latin Extended as a fallback for letters such as ł, ő, ș.
for (const [name, subset] of [["INTER", "latin"], ["INTER_EXT", "latin-ext"]]) {
  src += `export const ${name} = {\n`;
  for (const w of weights) {
    const b64 = fs.readFileSync(path.join(dir, `inter-${subset}-${w}-normal.woff`)).toString("base64");
    src += `  ${w}: "data:font/woff;base64,${b64}",\n`;
  }
  src += "};\n";
}
fs.writeFileSync(out, src);
fs.writeFileSync(out.replace(/\.mjs$/, ".d.mts"), "export declare const INTER: Record<number, string>;\nexport declare const INTER_EXT: Record<number, string>;\n");
console.log(`pdf fonts: ${weights.length} weights → ${path.relative(process.cwd(), out)}`);
